import { createHmac } from 'node:crypto';
import { describe, it, expect } from 'vitest';
import fixture from '../../../tests/fixtures/legacy/auth.json';

function verifyHs256(token: string, secret: string) {
  const [h, p, s] = token.split('.') as [string, string, string];
  const sig = createHmac('sha256', secret).update(`${h}.${p}`).digest('base64url');
  expect(sig).toBe(s);
  return JSON.parse(Buffer.from(p, 'base64url').toString());
}

describe('legacy auth fixture (generated by old Python libs)', () => {
  it('has the brief-required shape', () => {
    expect(fixture.password).toBe('LegacyPass1!');
    expect(fixture.argon2_hash).toMatch(/^\$argon2/);
    expect(fixture.bcrypt_hash).toMatch(/^\$2[aby]\$/);
  });
  it('tokens are HS256 with expected claims and clock-derived exp', () => {
    const access = verifyHs256(fixture.access_token, fixture.secret);
    expect(access).toMatchObject({ sub: '7', type: 'access', exp: fixture.clock + fixture.access_ttl_minutes * 60 });
    const refresh = verifyHs256(fixture.refresh_token, fixture.secret);
    expect(refresh).toMatchObject({ sub: '7', type: 'refresh', exp: fixture.clock + fixture.refresh_ttl_minutes * 60 });
    expect(verifyHs256(fixture.admin_access_token, fixture.secret)).toMatchObject({ sub: 'admin', admin: true, type: 'access' });
  });
});
