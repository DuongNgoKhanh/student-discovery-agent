"""Error codes raised by the engine module.

Follows contracts/error_codes.md (`PREFIX_CODE`):
- VAL_: invalid definition or answer input (400/422). Codes shared with the
  definition validator (evaluations/services/validator.py) reuse its names.
- REQ_: answer prefix violates an assessment business rule.
- SYS_: internal engine invariant failure (500); unreachable for a validated definition.
"""


class EngineErrorCode:
    # Definition validation (shared with the definition validator)
    INVALID_TYPE = "VAL_INVALID_TYPE"
    INVALID_FIELD = "VAL_INVALID_FIELD"
    MISSING_REQUIRED_FIELD = "VAL_MISSING_REQUIRED_FIELD"
    INVALID_SCHEMA_VERSION = "VAL_INVALID_SCHEMA_VERSION"
    UNSUPPORTED_RULE_SCHEMA = "VAL_UNSUPPORTED_RULE_SCHEMA"
    DUPLICATE_QUESTION_ID = "VAL_DUPLICATE_QUESTION_ID"
    DUPLICATE_OPTION_ID = "VAL_DUPLICATE_OPTION_ID"
    INVALID_INITIAL_QUESTION = "VAL_INVALID_INITIAL_QUESTION"
    INVALID_COVERAGE_CONFIG = "VAL_INVALID_COVERAGE_CONFIG"
    INVALID_MIN_ANSWERS = "VAL_INVALID_MIN_ANSWERS"
    INVALID_TIE_ORDER = "VAL_INVALID_TIE_ORDER"
    INVALID_BASELINE_COUNT = "VAL_INVALID_BASELINE_COUNT"
    BASELINE_QUESTION_NOT_IN_BANK = "VAL_BASELINE_QUESTION_NOT_IN_BANK"
    DUPLICATE_BASELINE_QUESTION = "VAL_DUPLICATE_BASELINE_QUESTION"
    INVALID_HOUSE_REF = "VAL_INVALID_HOUSE_REF"
    INVALID_ITEM_ORDER = "VAL_INVALID_ITEM_ORDER"
    HOUSE_QUESTION_COUNT_MISMATCH = "VAL_HOUSE_QUESTION_COUNT_MISMATCH"
    HOUSE_ITEM_ORDER_MISMATCH = "VAL_HOUSE_ITEM_ORDER_MISMATCH"
    INVALID_RATING = "VAL_INVALID_RATING"

    # Answer input validation
    UNKNOWN_QUESTION_ID = "VAL_UNKNOWN_QUESTION_ID"
    INVALID_OPTION_ID = "VAL_INVALID_OPTION_ID"
    RATING_MISMATCH = "VAL_RATING_MISMATCH"

    # Exception class defaults
    INVALID_ANSWER_PREFIX = "VAL_INVALID_ANSWER_PREFIX"
    UNSUPPORTED_DEFINITION = "VAL_UNSUPPORTED_DEFINITION"
    MISSING_MAPPING = "VAL_MISSING_MAPPING"

    # Assessment business rules
    QUESTION_ALREADY_ANSWERED = "REQ_QUESTION_ALREADY_ANSWERED"
    SEQUENCE_MISMATCH = "REQ_SEQUENCE_MISMATCH"
    ASSESSMENT_ALREADY_COMPLETED = "REQ_ASSESSMENT_ALREADY_COMPLETED"

    # Internal invariants
    ENGINE_ERROR = "SYS_ENGINE_ERROR"
    BANK_EXHAUSTED = "SYS_BANK_EXHAUSTED"
    ANTI_REPEAT_VIOLATION = "SYS_ANTI_REPEAT_VIOLATION"
    HOUSE_ITEMS_INVARIANT_VIOLATION = "SYS_HOUSE_ITEMS_INVARIANT_VIOLATION"
