"""The Studio tool catalog: generated from the registry into contracts/fixtures, read by web-ui and studio-api.

Run ``python -m agent_runtime.tools.catalog`` after adding or changing a tool; a unit test fails until you do.
"""
import json
from pathlib import Path

from agent_runtime.tools.kit import NoParams, json_schema
from agent_runtime.tools.registry import TOOLS

FIXTURE = Path(__file__).resolve().parents[5] / "contracts/fixtures/agent-tool-catalog.json"


def catalog_document() -> dict:
    tools = []
    for tool in TOOLS.values():
        has_params = tool.params is not NoParams
        tools.append({"name": tool.name, "version": tool.version, "kind": tool.kind, "label": tool.label,
                      "summary": tool.summary, "has_params": has_params,
                      "editor": (tool.editor or "json") if has_params else "none",
                      "params_schema": json_schema(tool.params) if has_params else None})
    return {"description": "Generated by `python -m agent_runtime.tools.catalog` from agent_runtime/tools/registry.py. "
                           "Do not edit by hand.", "tools": tools}


def main() -> None:
    FIXTURE.write_text(json.dumps(catalog_document(), ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
